import math

# Operasi akar dan pangkat
print(f"Kuadrat dari 10\t: {math.pow(10, 2)}")
print(f"Kubik dari 8\t: {math.pow(8, 1/3)}")
print(f"2 Pangkat 10\t: {math.pow(2, 10)}")

# Pembulatan
print(f"Rounded 10.5\t: {math.ceil(10.5)}")
print(f"Rounded 10.4\t: {math.floor(10.4)}")

# Logaritma
print(f"Log natural 10\t: {math.log(10)}")
print(f"Log basis 10\t: {math.log10(10)}")